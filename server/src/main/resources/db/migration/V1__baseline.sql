-- Administrator receives the complete versioned permission catalog without a
-- seeded user/password. Deployment bootstrap must create the first account via
-- a separate one-time secret-bearing process.
INSERT INTO df_etl.role_permission (role_id, permission_code)
SELECT r.id, p.code
FROM df_etl.security_role r
CROSS JOIN df_etl.security_permission p
WHERE r.code = 'ROLE_ADMIN';

-- Operator: operational management excluding account/RBAC administration,
-- audit sensitive export and direct sensitive raw-value access.
INSERT INTO df_etl.role_permission (role_id, permission_code)
SELECT r.id, p.code
FROM df_etl.security_role r
JOIN df_etl.security_permission p ON (
    p.domain IN ('dashboard','institution','system_instance','datasource','dataset','route','sync_task','sync_execution','message_outbox','precheck','validation','alert','setting','registry','validation_policy','doris_table','external_client','type_mapping')
    AND p.code NOT IN ('precheck.detail.reveal','precheck.detail.export_sensitive','audit.export')
)
WHERE r.code = 'ROLE_OPERATOR';

-- Auditor: read permissions, audit access and non-sensitive exports only.
INSERT INTO df_etl.role_permission (role_id, permission_code)
SELECT r.id, p.code
FROM df_etl.security_role r
JOIN df_etl.security_permission p ON (
    p.code IN (
        'dashboard.view','institution.view','system_instance.view','datasource.view','dataset.view','route.view',
        'sync_task.view','sync_execution.view','sync_execution.export','message_outbox.view',
        'precheck.view','precheck.summary.view','precheck.summary.export','precheck.detail.view','precheck.detail.export',
        'validation.view','validation.export','alert.view','log.view','audit.view','audit.export','setting.view',
        'registry.view','validation_policy.view','doris_table.view','doris_table.ddl.preview',
        'external_client.view','type_mapping.view','security.account.view'
    )
)
WHERE r.code = 'ROLE_AUDITOR';

-- Viewer: non-sensitive read-only visibility.
