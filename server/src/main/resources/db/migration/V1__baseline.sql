CREATE FUNCTION df_etl.assert_sync_task_version_dataset_contract()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_business_key_count integer;
    v_incremental_field_code varchar(100);
BEGIN
    SELECT business_key_count, incremental_field_code
      INTO STRICT v_business_key_count, v_incremental_field_code
      FROM df_etl.standard_dataset_version
     WHERE id = NEW.dataset_version_id
       AND dataset_id = NEW.dataset_id;

    IF v_business_key_count = 0 THEN
        IF NEW.task_kind <> 'FULL_ONLY'
           OR NEW.write_mode <> 'REPLACE_INSTITUTION_SCOPE'
           OR NEW.doris_key_model <> 'DUPLICATE_KEY'
           OR NEW.incremental_field_code IS NOT NULL
           OR NEW.validation_method <> 'ROW_COUNT' THEN
            RAISE EXCEPTION 'dataset version % has no business key and requires FULL_ONLY + REPLACE_INSTITUTION_SCOPE + DUPLICATE_KEY + ROW_COUNT', NEW.dataset_version_id
                USING ERRCODE = '23514';
        END IF;
    ELSIF v_incremental_field_code IS NOT NULL THEN
        IF NEW.task_kind <> 'FULL_THEN_INCREMENTAL'
           OR NEW.write_mode <> 'UPSERT'
           OR NEW.doris_key_model <> 'UNIQUE_KEY'
           OR lower(NEW.incremental_field_code) IS DISTINCT FROM lower(v_incremental_field_code) THEN
            RAISE EXCEPTION 'dataset version % has a business key and incremental field %, and requires FULL_THEN_INCREMENTAL + UPSERT + UNIQUE_KEY with the same incremental field', NEW.dataset_version_id, v_incremental_field_code
                USING ERRCODE = '23514';
        END IF;
    ELSE
        IF NEW.task_kind <> 'FULL_ONLY'
           OR NEW.write_mode <> 'UPSERT'
           OR NEW.doris_key_model <> 'UNIQUE_KEY'
           OR NEW.incremental_field_code IS NOT NULL THEN
            RAISE EXCEPTION 'dataset version % has a business key without an incremental field and requires FULL_ONLY + UPSERT + UNIQUE_KEY', NEW.dataset_version_id
                USING ERRCODE = '23514';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

