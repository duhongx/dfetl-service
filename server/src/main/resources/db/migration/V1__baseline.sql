CREATE FUNCTION df_etl.validate_known_system_setting()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_integer bigint;
BEGIN
    IF NEW.setting_key = 'scheduler.max_concurrent' THEN
        v_integer := (NEW.value_json #>> '{}')::bigint;
        IF NEW.value_type <> 'INTEGER' OR v_integer NOT BETWEEN 1 AND 64 THEN
            RAISE EXCEPTION 'scheduler.max_concurrent must be an integer between 1 and 64' USING ERRCODE = '23514';
        END IF;
    ELSIF NEW.setting_key = 'precheck.max_parallel_routes' THEN
        v_integer := (NEW.value_json #>> '{}')::bigint;
        IF NEW.value_type <> 'INTEGER' OR v_integer NOT BETWEEN 1 AND 32 THEN
            RAISE EXCEPTION 'precheck.max_parallel_routes must be an integer between 1 and 32' USING ERRCODE = '23514';
        END IF;
    ELSIF NEW.setting_key = 'precheck.issue_detail_retention_days' THEN
        v_integer := (NEW.value_json #>> '{}')::bigint;
        IF NEW.value_type <> 'INTEGER' OR v_integer NOT BETWEEN 1 AND 30 THEN
            RAISE EXCEPTION 'precheck.issue_detail_retention_days must be 1..30' USING ERRCODE = '23514';
        END IF;
    ELSIF NEW.setting_key IN ('precheck.pass_raw_retention_days', 'precheck.failed_raw_retention_days') THEN
        v_integer := (NEW.value_json #>> '{}')::bigint;
        IF NEW.value_type <> 'INTEGER' OR v_integer NOT BETWEEN 0 AND 7 THEN
            RAISE EXCEPTION '% must be 0..7', NEW.setting_key USING ERRCODE = '23514';
        END IF;
    ELSIF NEW.setting_key IN ('export.retention_hours', 'doris.scope_backup_retention_hours') THEN
        v_integer := (NEW.value_json #>> '{}')::bigint;
        IF NEW.value_type <> 'INTEGER' OR v_integer NOT BETWEEN 1 AND 168 THEN
            RAISE EXCEPTION '% must be 1..168', NEW.setting_key USING ERRCODE = '23514';
        END IF;
    ELSIF NEW.setting_key = 'outbox.max_attempts' THEN
        v_integer := (NEW.value_json #>> '{}')::bigint;
        IF NEW.value_type <> 'INTEGER' OR v_integer NOT BETWEEN 1 AND 100 THEN
            RAISE EXCEPTION 'outbox.max_attempts must be 1..100' USING ERRCODE = '23514';
        END IF;
    ELSIF NEW.setting_key = 'outbox.publishing_timeout_seconds' THEN
        v_integer := (NEW.value_json #>> '{}')::bigint;
        IF NEW.value_type <> 'INTEGER' OR v_integer NOT BETWEEN 30 AND 3600 THEN
            RAISE EXCEPTION 'outbox.publishing_timeout_seconds must be 30..3600' USING ERRCODE = '23514';
        END IF;
    ELSIF NEW.setting_key = 'medical_community.code' THEN
        IF NEW.value_type <> 'STRING' OR length(NEW.value_json #>> '{}') > 64 THEN
            RAISE EXCEPTION 'medical_community.code must be a string of at most 64 characters' USING ERRCODE = '23514';
        END IF;
    ELSIF NEW.setting_key = 'medical_community.name' THEN
        IF NEW.value_type <> 'STRING' OR length(NEW.value_json #>> '{}') > 200 THEN
            RAISE EXCEPTION 'medical_community.name must be a string of at most 200 characters' USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_system_setting_validate
BEFORE INSERT OR UPDATE OF value_type, value_json ON df_etl.system_setting
FOR EACH ROW EXECUTE FUNCTION df_etl.validate_known_system_setting();

