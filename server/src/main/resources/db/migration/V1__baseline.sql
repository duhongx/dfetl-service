CREATE FUNCTION df_etl.assert_delete_apply_dry_run()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    referenced_operation varchar(16);
    referenced_status varchar(20);
    anchor_validation_type varchar(32);
    anchor_validation_status varchar(20);
    anchor_validation_result varchar(16);
BEGIN
    SELECT validation_type, status, result
      INTO STRICT anchor_validation_type, anchor_validation_status, anchor_validation_result
      FROM df_etl.validation_run
     WHERE id = NEW.validation_run_id;

    IF anchor_validation_type <> 'DELETE_RECONCILIATION'
       OR anchor_validation_status <> 'COMPLETED'
       OR anchor_validation_result <> 'MISMATCH' THEN
        RAISE EXCEPTION 'Delete apply operations require a COMPLETED + MISMATCH DELETE_RECONCILIATION validation run'
            USING ERRCODE = '23514';
    END IF;

    IF TG_OP = 'UPDATE' THEN
        IF OLD.operation = 'DRY_RUN'
           AND OLD.status = 'SUCCEEDED'
           AND NEW.status IS DISTINCT FROM OLD.status
           AND EXISTS (SELECT 1 FROM df_etl.delete_apply_run WHERE dry_run_id = OLD.id) THEN
            RAISE EXCEPTION 'Referenced successful DRY_RUN cannot leave SUCCEEDED status'
                USING ERRCODE = '23514';
        END IF;
    END IF;

    IF NEW.operation = 'APPLY' THEN
        SELECT operation, status
          INTO referenced_operation, referenced_status
          FROM df_etl.delete_apply_run
         WHERE id = NEW.dry_run_id
           AND validation_run_id = NEW.validation_run_id;

        IF referenced_operation IS DISTINCT FROM 'DRY_RUN'
           OR referenced_status IS DISTINCT FROM 'SUCCEEDED' THEN
            RAISE EXCEPTION 'APPLY must reference a SUCCEEDED DRY_RUN for the same validation_run_id'
                USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE UNIQUE INDEX uq_delete_apply_effective_apply ON df_etl.delete_apply_run(validation_run_id)
    WHERE operation = 'APPLY' AND status IN ('PENDING','RUNNING','SUCCEEDED','STATE_UNKNOWN');
CREATE INDEX idx_delete_apply_validation_requested ON df_etl.delete_apply_run(validation_run_id, requested_at DESC);
CREATE TRIGGER trg_delete_apply_requires_successful_dry_run
BEFORE INSERT OR UPDATE OF operation, dry_run_id, validation_run_id, status ON df_etl.delete_apply_run
FOR EACH ROW EXECUTE FUNCTION df_etl.assert_delete_apply_dry_run();

