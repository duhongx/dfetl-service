CREATE FUNCTION df_etl.reject_immutable_change()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'table %.% is immutable; create a new version or run instead',
        TG_TABLE_SCHEMA, TG_TABLE_NAME
        USING ERRCODE = '55000';
END;
$$;

CREATE FUNCTION df_etl.assert_current_version_set()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_current_version_id bigint;
BEGIN
    EXECUTE format('SELECT current_version_id FROM %I.%I WHERE id = $1', TG_TABLE_SCHEMA, TG_TABLE_NAME)
       INTO v_current_version_id
       USING NEW.id;
    IF v_current_version_id IS NULL THEN
        RAISE EXCEPTION '%.% id % must reference a current version before transaction commit',
            TG_TABLE_SCHEMA, TG_TABLE_NAME, NEW.id
            USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;

